/**
 * 获取随机Buff语录
 * @returns {string} 随机返回一条Buff语录
 */
export function getRandomBuff() {
  const randomIndex = Math.floor(Math.random() * buffLibrary.length);
  return buffLibrary[randomIndex];
}

/**
 * 获取指定数量的随机Buff语录(不重复)
 * @param {number} count 需要获取的数量
 * @returns {string[]} Buff语录数组
 */
export function getRandomBuffs(count = 1) {
  const shuffled = [...buffLibrary].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, Math.min(count, buffLibrary.length));
}
